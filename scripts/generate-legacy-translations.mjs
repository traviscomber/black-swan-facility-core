import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import ts from "typescript"

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, "..")
const sourcePath = resolve(root, "lib/translations/legacy-language-context.source.txt")
const outputPath = resolve(root, "lib/translations/legacy-generated.ts")
const sourceText = readFileSync(sourcePath, "utf8")
const sourceFile = ts.createSourceFile(sourcePath, sourceText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)

function propertyName(node) {
  if (ts.isStringLiteral(node) || ts.isNumericLiteral(node)) return node.text
  if (ts.isIdentifier(node)) return node.text
  throw new Error(`Unsupported translation property name: ${node.getText(sourceFile)}`)
}

function findTranslationsObject() {
  for (const statement of sourceFile.statements) {
    if (!ts.isVariableStatement(statement)) continue
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || declaration.name.text !== "translations") continue
      if (!declaration.initializer || !ts.isObjectLiteralExpression(declaration.initializer)) {
        throw new Error("Legacy translations declaration is not an object literal")
      }
      return declaration.initializer
    }
  }
  throw new Error("Legacy translations declaration was not found")
}

function collectLanguage(languageNode, language) {
  if (!ts.isPropertyAssignment(languageNode) || !ts.isObjectLiteralExpression(languageNode.initializer)) {
    throw new Error(`Legacy language ${language} is not an object literal`)
  }

  const entries = new Map()
  let duplicateCount = 0

  for (const property of languageNode.initializer.properties) {
    if (!ts.isPropertyAssignment(property)) {
      throw new Error(`Unsupported property in ${language}: ${property.getText(sourceFile)}`)
    }
    const key = propertyName(property.name)
    const value = property.initializer
    if (!ts.isStringLiteral(value) && !ts.isNoSubstitutionTemplateLiteral(value)) {
      throw new Error(`Translation ${language}.${key} must be a static string literal`)
    }
    if (entries.has(key)) duplicateCount += 1
    entries.set(key, value.text)
  }

  return { entries, duplicateCount }
}

const translationsObject = findTranslationsObject()
const languages = new Map()
for (const property of translationsObject.properties) {
  if (!ts.isPropertyAssignment(property)) continue
  const language = propertyName(property.name)
  if (language !== "en" && language !== "es") continue
  languages.set(language, collectLanguage(property, language))
}

for (const language of ["en", "es"]) {
  if (!languages.has(language)) throw new Error(`Legacy translations are missing ${language}`)
}

function renderLanguage(language) {
  const { entries } = languages.get(language)
  const rows = [...entries.entries()].map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  return `  ${language}: {\n${rows.join("\n")}\n  },`
}

const output = `// AUTO-GENERATED by scripts/generate-legacy-translations.mjs.\n// Do not edit this file directly; edit the canonical source or migrate keys to modular dictionaries.\n\nexport const translations = {\n${renderLanguage("en")}\n${renderLanguage("es")}\n} satisfies Record<"en" | "es", Record<string, string>>\n`

writeFileSync(outputPath, output, "utf8")

const duplicateTotal = languages.get("en").duplicateCount + languages.get("es").duplicateCount
console.log(`Generated legacy translations: ${languages.get("en").entries.size} en, ${languages.get("es").entries.size} es, ${duplicateTotal} duplicate definitions collapsed with last-value semantics.`)
